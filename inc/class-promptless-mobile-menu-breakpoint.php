<?php
/**
 * Mobile Menu Breakpoint Customizer Setting
 *
 * Adds a Customizer control that lets the site owner choose the viewport width
 * at which the main navigation collapses into the mobile hamburger menu. The
 * theme defaults to 768px (iPad portrait) but sites with long menus (8+ items,
 * multi-word items, or a prominent CTA button) often need to collapse later —
 * e.g., 1024px (iPad landscape) so the menu doesn't overflow horizontally on
 * smaller tablets.
 *
 * Architecture
 * ============
 * The killer constraint: CSS custom properties cannot be used inside @media
 * query conditions. `@media (min-width: var(--breakpoint))` is invalid CSS in
 * every browser. The breakpoint pixel value MUST be a literal in the CSS the
 * browser parses. That rules out a "pure CSS variable" approach.
 *
 * Strategy (final, after v1 cascade-flaw lesson):
 *
 * 1. assets/css/header.css contains NO breakpoint-dependent @media rules.
 *    All 13 @media (min-width: 768px) and @media (max-width: 767px) blocks
 *    live in a separate file: assets/css/header-breakpoint.css. This split
 *    is generated by scripts/split-header-breakpoint.js and is the single
 *    canonical home for breakpoint-dependent CSS.
 *
 * 2. Promptless_Assets ALWAYS enqueues header.min.css. Then:
 *      - When the user is on the DEFAULT breakpoint (768), Assets also
 *        enqueues the static header-breakpoint.min.css. The frontend
 *        renders exactly as it did pre-customizer.
 *      - When the user picks a NON-DEFAULT breakpoint, Assets SKIPS the
 *        static file and this class emits an inline <style> block in <head>
 *        with the 13 rules rewritten at the chosen breakpoint.
 *
 * 3. Only ONE source of breakpoint rules is ever in the cascade at a time.
 *    There is no "original 768 rule still firing in the gap" failure mode —
 *    the original rules are physically not in the stylesheet when the user
 *    diverges from default.
 *
 * 4. The extracted-and-rewritten CSS is cached as a WordPress transient
 *    keyed on (breakpoint_value, header-breakpoint.css_mtime). When that
 *    source file is edited the mtime changes, the cache key changes, the
 *    cache misses, regeneration happens. When the user picks a different
 *    breakpoint the value changes, same outcome. With 5 allowed values
 *    there are at most 5 cache entries in steady state.
 *
 * 5. A body class `promptless-menu-breakpoint-{value}` is added so
 *    JavaScript in navigation.js can read the value without parsing CSS or
 *    duplicating the setting in two places.
 *
 * Why this split rather than runtime override
 * ===========================================
 * An earlier draft (1.1.7 dev branch) tried to leave the 13 blocks in
 * header.css and emit an inline OVERRIDE block at the user's chosen
 * breakpoint. That approach is fundamentally broken because CSS @media
 * rules are ADDITIVE, not REPLACEABLE: a viewport in the gap range (e.g.
 * 900px when user picked 1024) matches BOTH the original (min-width: 768px)
 * block AND nothing in the override. The desktop nav stays visible AND the
 * hamburger stays hidden — broken UX with no path to a clean fix. The split
 * is the only correct architecture: physically own where the rules live.
 *
 * The regex deliberately excludes @media (max-width: 782px) — those queries
 * are WordPress admin bar offsets, a separate concern that should always
 * stay anchored to 782 regardless of the user's menu breakpoint choice.
 *
 * @package Promptless_Theme
 * @since 1.1.8
 */

