/**
 * One-off splitter: extract breakpoint-dependent @media rules from header.css
 * into a separate header-breakpoint.css file.
 *
 * Why this exists
 * ===============
 * The mobile-menu-breakpoint Customizer setting (1.1.8) lets the user pick
 * the viewport width where the main nav collapses. Implementing that requires
 * a single canonical source for the breakpoint-dependent CSS so the runtime
 * generator can rewrite the pixel values without colliding with the original
 * rules — which it WOULD if header.css still contained them at the hardcoded
 * 768px boundary.
 *
 * The split:
 *   - header.css              → keeps everything EXCEPT @media rules whose
 *                                condition mentions min-width: 768px or
 *                                max-width: 767px.
 *   - header-breakpoint.css   → contains exactly those rules.
 *
 * Excluded from extraction: @media (max-width: 782px) — WordPress admin-bar
 * offset, anchored to WP's own breakpoint, never moves with the menu setting.
 *
 * Usage
 * =====
 * Run ONCE during the 1.1.7 → 1.1.8 refactor:
 *
 *     node scripts/split-header-breakpoint.js
 *
 * The script is idempotent — running it twice on already-split files is a
 * no-op because no matching @media blocks remain in header.css.
 *
 * @package Promptless_Theme
 * @since 1.1.8
 */

const fs = require('fs');
const path = require('path');
const postcss = require('postcss');

const themeRoot = path.resolve(__dirname, '..');
const sourcePath = path.join(themeRoot, 'assets/css/header.css');
const targetPath = path.join(themeRoot, 'assets/css/header-breakpoint.css');

/**
 * Decide whether a given @media query targets the menu breakpoint.
 *
 * Matches:
 *   - (min-width: 768px)
 *   - (max-width: 767px)
 *   - compound queries containing either, e.g.
 *     (min-width: 768px) and (orientation: landscape)
 *
 * Explicitly does NOT match (max-width: 782px) — WordPress admin-bar.
 *
 * @param {string} mediaParams The value after `@media`, e.g. "(min-width: 768px)".
 * @returns {boolean}
 */
function isMenuBreakpointMedia(mediaParams) {
    // Reject the admin-bar query no matter what else is in there.
    if (/max-width:\s*782px/.test(mediaParams)) {
        return false;
    }
    return /min-width:\s*768px/.test(mediaParams)
        || /max-width:\s*767px/.test(mediaParams);
}

async function split() {
    if (!fs.existsSync(sourcePath)) {
        console.error(`✗ Source file not found: ${sourcePath}`);
        process.exit(1);
    }

    const source = fs.readFileSync(sourcePath, 'utf8');
    const root = postcss.parse(source, { from: sourcePath });

    const extractedNodes = [];

    // Walk top-level children; we only split TOP-LEVEL @media queries since
    // nested ones (e.g. inside @supports) are an edge case header.css doesn't use.
    root.each((node) => {
        if (node.type === 'atrule' && node.name === 'media' && isMenuBreakpointMedia(node.params)) {
            extractedNodes.push(node.clone());
            node.remove();
        }
    });

    if (extractedNodes.length === 0) {
        console.log('✓ No matching @media blocks found — file already split, nothing to do.');
        return;
    }

    // Build the extracted file with a clear provenance header.
    const extractedHeader = `/*!
 * Promptless Theme — Header breakpoint stylesheet
 *
 * Auto-generated by scripts/split-header-breakpoint.js from header.css.
 * Contains ONLY the @media queries that control where the main navigation
 * collapses from desktop layout to the mobile hamburger drawer.
 *
 * DO NOT add new rules to this file by hand. Add them to header.css inside
 * the appropriate @media (min-width: 768px) or @media (max-width: 767px)
 * block, then run:
 *
 *     node scripts/split-header-breakpoint.js
 *     npm run build:css
 *
 * The Customizer "Mobile Menu Breakpoint" setting reads THIS file (not
 * header.css) when regenerating override CSS at the user's chosen
 * breakpoint, so any rule placed here participates in the override
 * automatically.
 *
 * @since 1.1.8
 */
`;

    // Render the extracted rules back to CSS preserving their formatting.
    const extractedRoot = postcss.root();
    extractedNodes.forEach((n) => extractedRoot.append(n));
    const extractedCss = extractedHeader + '\n' + extractedRoot.toString() + '\n';

    fs.writeFileSync(targetPath, extractedCss);

    // Write the trimmed header.css back, preserving everything that wasn't extracted.
    const trimmedCss = root.toString();
    fs.writeFileSync(sourcePath, trimmedCss);

    console.log(`✓ Extracted ${extractedNodes.length} @media block(s)`);
    console.log(`  → ${path.relative(themeRoot, targetPath)}`);
    console.log(`✓ Trimmed source`);
    console.log(`  → ${path.relative(themeRoot, sourcePath)}`);

    const originalSize = Buffer.byteLength(source, 'utf8');
    const trimmedSize = Buffer.byteLength(trimmedCss, 'utf8');
    const extractedSize = Buffer.byteLength(extractedCss, 'utf8');

    console.log('');
    console.log(`  header.css:           ${(originalSize / 1024).toFixed(1)}KB → ${(trimmedSize / 1024).toFixed(1)}KB`);
    console.log(`  header-breakpoint.css: ${(extractedSize / 1024).toFixed(1)}KB`);
    console.log('');
    console.log('Next step: run `npm run build:css` to regenerate the .min.css files.');
}

split().catch((err) => {
    console.error('✗ Splitter failed:', err);
    process.exit(1);
});
